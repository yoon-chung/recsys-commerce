"""Golden set — (pack, item, question, response, label) JSONL.

용도:
- LLM-as-Judge 회귀 채점의 정답/기준점
- Calibration 학습 라벨 (label_supported를 0/1로 사용)

label_supported는 수작업으로 검토 (응답이 evidence에 의해 실제로 뒷받침되는가).
make_starter_golden_set()은 mock으로 ~10개 자동 생성 — 팀이 직접 검토·수정 권장.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Iterator

from pydantic import BaseModel

from advisor.schema import AdvisorResponse
from evidence_pack.schema import EvidencePack


class GoldenItem(BaseModel):
    """단일 평가 표본."""

    pack: EvidencePack
    item_id: str
    question_key: str
    response: AdvisorResponse
    label_supported: bool  # 수작업 라벨: 응답이 실제로 evidence에 의해 뒷받침되는가
    note: str = ""


def iter_golden_set(path: str | Path) -> Iterator[GoldenItem]:
    """JSONL 스트림 로드."""
    p = Path(path)
    if not p.exists():
        return
    with p.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                yield GoldenItem.model_validate_json(line)


def save_golden_set(items: list[GoldenItem], path: str | Path) -> int:
    """JSONL 저장. 작성한 행 수 반환."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("w", encoding="utf-8") as f:
        for it in items:
            f.write(it.model_dump_json() + "\n")
    return len(items)


def make_starter_golden_set(
    n: int = 10,
    out_path: str | Path = "data/golden_set.jsonl",
) -> int:
    """MockAdapter로 mock 응답을 만들고 모두 label_supported=True로 저장.

    팀이 직접 열어 label을 수정·보완하는 게 정상 사용법.
    """
    from advisor.mock_client import MockClient
    from evidence_pack import MockAdapter, build_evidence_pack, iter_evidence_pack
    from trust_gate import apply_hard_gate

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    tmp_pack = out_path.parent / "_starter_pack.jsonl"
    mock = MockAdapter(top_k=10, seed=42)
    build_evidence_pack(mock, mock, tmp_pack, max_users=max(5, n // 3 + 1))

    client = MockClient()
    items: list[GoldenItem] = []
    questions = ["why", "should_buy", "fit_preference", "revisit", "category_trend", "promotion_candidate"]

    for pack in iter_evidence_pack(tmp_pack):
        for rec in pack.recommendations[:2]:
            for qk in questions:
                if len(items) >= n:
                    break
                resp = client.generate(pack, rec.item_id, qk)
                apply_hard_gate(pack, resp)
                items.append(GoldenItem(
                    pack=pack, item_id=rec.item_id, question_key=qk,
                    response=resp,
                    # mock은 항상 evidence 안의 신호만 인용하므로 True. 팀이 검토해 수정.
                    label_supported=True,
                    note="auto-generated by make_starter_golden_set; please review & edit label",
                ))
            if len(items) >= n:
                break
        if len(items) >= n:
            break

    tmp_pack.unlink(missing_ok=True)
    save_golden_set(items, out_path)
    return len(items)


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="data/golden_set.jsonl")
    parser.add_argument("--n", type=int, default=10)
    args = parser.parse_args()
    n = make_starter_golden_set(args.n, args.out)
    print(f"Wrote {n} starter golden items to {args.out}")
    print("  → 각 항목의 label_supported를 팀이 직접 검토·수정해 주세요.")
